/** Root-relative (web) vs Electron-relative ("./…", file://) scenario asset path. */
export function scenarioAssetPath(entry: BundledScenario): string {
  const isFile = typeof window !== "undefined" && window.location.protocol === "file:";
  const base = isFile ? "./scenarios" : "/scenarios";
  return `${base}/${entry.category}/${entry.file}`;
}
